import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { createRequire } from "node:module";
import pg from "pg";
import { loadModule } from "../tests/support/load-typescript.mjs";
const require=createRequire(import.meta.url);
require("@next/env").loadEnvConfig(process.cwd());
const url=new URL(process.env.DIRECT_DATABASE_URL || process.env.DATABASE_URL);
if (process.env.REVIEW_TEST_HOST) url.hostname=process.env.REVIEW_TEST_HOST;
const client=new pg.Client({connectionString:url.toString(),connectionTimeoutMillis:15000});
const validation=loadModule("../src/lib/review-validation.ts");
const store=loadModule("../src/lib/review-store.ts",{"server-only":{},"@/lib/review-db":{reviewDatabase:()=>client},"@/lib/review-validation":validation});
const callSid=`CA${randomBytes(16).toString("hex")}`;
const recordingSid=`RE${randomBytes(16).toString("hex")}`;
const user=`user_storage_test_${randomBytes(8).toString("hex")}`;
try {
  await client.connect();await client.query("BEGIN");
  await store.storeCall({callSid,operatorId:user,to:"+61412345678",from:"+12125550123",country:"AU",startedAt:new Date(),status:"completed",duration:120});
  assert.equal(await store.getReview(callSid,"user_other"),null);
  assert.equal(await store.saveReview(callSid,"user_other",{notes:"Forbidden",rating:1,bookmarks:[]}),false);
  const recording={sid:recordingSid,callSid,status:"completed",duration:120,channels:2,createdAt:new Date()};
  await store.storeRecording(recording);
  assert.equal((await store.getReview(callSid,user)).recordings.length,0,"recording metadata requires consent");
  const token=await store.acquireRecordingLease(callSid,user,true);
  assert.ok(token);
  assert.equal(await store.acquireRecordingLease(callSid,user,true),null);
  await store.releaseRecordingLease(callSid,"wrong-token");
  assert.equal(await store.acquireRecordingLease(callSid,user,true),null);
  await store.releaseRecordingLease(callSid,token);
  await store.storeRecording(recording);
  const owned=await store.getOwnedRecording(recordingSid,user);
  assert.ok(owned);assert.equal(await store.getOwnedRecording(recordingSid,"user_other"),null);
  const expiry=owned.expiresAt;
  await store.storeRecording({...recording,status:"in-progress",duration:0});
  assert.equal((await store.getOwnedRecording(recordingSid,user)).status,"completed","late recording updates cannot regress final status");
  await store.storeRecording({...recording,createdAt:new Date(Date.now()+86400000)});
  assert.equal((await store.getOwnedRecording(recordingSid,user)).expiresAt,expiry,"callbacks cannot extend retention");
  const notes="Review text: '); DROP TABLE veilcall_calls; --";
  await store.saveReview(callSid,user,{notes,rating:4,bookmarks:[{id:"moment",recordingSid,seconds:15,note:"Check opening"}]});
  assert.equal((await store.getReview(callSid,user)).notes,notes);
  await store.storeCall({callSid,operatorId:user,to:"",from:"",country:"",startedAt:new Date(),status:"ringing",duration:0});
  assert.equal((await store.getReview(callSid,user)).status,"completed","late events cannot regress final status");
  await store.tombstoneRecording(recordingSid);
  await store.storeRecording(recording);
  assert.ok((await store.getOwnedRecording(recordingSid,user)).deletedAt,"callbacks cannot restore deleted audio");
  assert.ok((await store.expiredRecordings()).includes(recordingSid));
  await store.finishRecordingDeletion(recordingSid);
  assert.equal((await store.getOwnedRecording(recordingSid,user)).status,"deleted");
  for(let i=0;i<22;i++)await store.storeCall({callSid:`CA${randomBytes(16).toString("hex")}`,operatorId:user,to:"+442079460123",from:"+12125550123",country:"GB",startedAt:new Date(Date.now()-i*60000),status:"completed",duration:60});
  const first=await store.listReviews(user);
  assert.equal(first.items.length,20);assert.ok(first.nextCursor);
  const next=await store.listReviews(user,JSON.parse(Buffer.from(first.nextCursor,"base64url").toString()));
  assert.equal(next.items.length,3);assert.ok(!next.items.some((call)=>first.items.some((old)=>old.callSid===call.callSid)));
  const liveSid=`CA${randomBytes(16).toString("hex")}`,liveRecording=`RE${randomBytes(16).toString("hex")}`;
  await store.storeCall({callSid:liveSid,operatorId:user,to:"+61412345678",from:"+12125550123",country:"AU",startedAt:new Date(),status:"in-progress",duration:0});
  const liveToken=await store.acquireRecordingLease(liveSid,user,true);await store.releaseRecordingLease(liveSid,liveToken);
  const inflight={sid:liveRecording,callSid:liveSid,status:"in-progress",duration:0,channels:2,createdAt:new Date(),controlConfirmed:true};
  await store.storeRecording(inflight);
  await store.storeRecording({...inflight,status:"processing",controlConfirmed:false});
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"in-progress","processing reads retain confirmed active state");
  await store.storeRecording({...inflight,status:"paused"});
  await store.storeRecording({...inflight,status:"processing",controlConfirmed:false});
  await store.storeRecording({...inflight,controlConfirmed:false});
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"paused","reads and late start callbacks cannot undo pause");
  await store.storeRecording(inflight);
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"in-progress","confirmed resume replaces paused state");
  await store.storeRecording({...inflight,status:"stopped"});
  await store.storeRecording({...inflight,status:"processing",controlConfirmed:false});
  await store.storeRecording({...inflight,controlConfirmed:false});
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"stopped","reads cannot reactivate a stopped recording");
  await store.storeRecording({...inflight,status:"paused",controlConfirmed:false});
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"stopped","stale paused reads cannot reactivate a stopped recording");
  await store.storeCall({callSid:liveSid,operatorId:user,to:"",from:"",country:"",startedAt:new Date(),status:"completed",duration:60});
  await store.storeRecording({...inflight,status:"processing",controlConfirmed:false});
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"processing","ended calls leave the in-flight state");
  await store.storeRecording({...inflight,status:"completed",duration:60,controlConfirmed:false});
  assert.equal((await store.getOwnedRecording(liveRecording,user)).status,"completed");
  console.log("Database integration passed: ownership, consent, concurrency, retention, deletion, notes, final outcomes, and pagination.");
} catch {
  console.error("Database integration failed. No credentials were logged; all test writes are rolled back.");process.exitCode=1;
} finally {await client.query("ROLLBACK").catch(()=>{});await client.end();}
